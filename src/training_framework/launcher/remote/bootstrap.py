"""Generates the standard-library programs that run on a target before (or
without) any environment: `bootstrap.py` (building block B10) and the `host`
scheduler's `host_runner.py`. Each is one file bundling the same modules the
workstation uses, so lease, probe, filesystem, and preflight logic exist
once."""

from __future__ import annotations

import inspect
import re

from training_framework.launcher import EXECUTION_PROTOCOL_VERSION
from training_framework.launcher.remote import bootstrap_main, host_runner, lease, preflight, runtime

#: One-line imports between bundled modules; in the single file the names
#: they import are already defined, so the lines are removed.
_PACKAGE_IMPORT = re.compile(
    r"^from training_framework\.(?:launcher|hpc)(\.\w+)+ import .*$", re.MULTILINE)
BUNDLED_MODULES = (runtime, lease, preflight, bootstrap_main)
RUNNER_MODULES = (runtime, lease, host_runner)


def _bundle(modules) -> str:
    parts = [
        "#!/usr/bin/env python3",
        '"""Generated by training_framework.launcher; do not edit."""',
        f"PROTOCOL_VERSION = {EXECUTION_PROTOCOL_VERSION}",
    ]
    for module in modules:
        source = _PACKAGE_IMPORT.sub("", inspect.getsource(module))
        parts.append(f"# --- {module.__name__} ---\n{source}")
    parts.append('if __name__ == "__main__":\n    sys.exit(main())')
    return "\n\n".join(parts) + "\n"


def render_bootstrap() -> str:
    return _bundle(BUNDLED_MODULES)


def render_runner() -> str:
    return _bundle(RUNNER_MODULES)
